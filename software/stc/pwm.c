/*   Gear  4 ( 40%): 256 - 102 = 154 = 0x9A                                 */
/*   Gear  5 ( 50%): 256 - 128 = 128 = 0x80                                 */
/*   Gear  6 ( 60%): 256 - 153 = 103 = 0x67                                 */
/*   Gear  7 ( 70%): 256 - 179 =  77 = 0x4D                                 */
/*   Gear  8 ( 80%): 256 - 204 =  52 = 0x34                                 */
/*   Gear  9 ( 90%): 256 - 230 =  26 = 0x1A                                 */
/*   Gear 10 (100%): 256 - 256 =   0 = 0x00（全高）                         */
